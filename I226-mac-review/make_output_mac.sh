#!/bin/bash
# Writes notes/wormhole_evolution/constraint_plateau_output.txt from the stored runs of I226-rpi5 (run from notes/wormhole_evolution of the worktree).
RAWRUNS=$HOME/Source/negative-mass-raw/I226-rpi5/runs
PY=/Users/nathan/Source/negative-mass/.venv/bin/python
export NUMBA_NUM_THREADS=1
{
echo "# constraint_plateau_output.txt: output of constraint_plateau.py on the runs of record of negative-mass-raw I226-rpi5 (#226)."
echo "# generated by I226-rpi5/make_output.sh: controls, analyze, then each mutation (analysis mutations filtered to their verdict lines)."
echo; echo "## python3 constraint_plateau.py controls"
$PY constraint_plateau.py controls; echo "exit $?"
echo; echo "## python3 constraint_plateau.py analyze --raw=I226-rpi5/runs"
$PY constraint_plateau.py analyze --raw=$RAWRUNS; echo "exit $?"
for m in cons_sign diag_S rk4_step quad_h; do
  echo; echo "## python3 constraint_plateau.py controls --mutate=$m"
  $PY constraint_plateau.py controls --mutate=$m | cut -c1-300; echo "exit ${PIPESTATUS[0]}"
done
for m in static_noise256 quad_as_double noise_inert ray_pert spike corner model_exp; do
  echo; echo "## python3 constraint_plateau.py analyze --raw=I226-rpi5/runs --mutate=$m   (lines [pass]/[FAIL] and the mutation line)"
  $PY constraint_plateau.py analyze --raw=$RAWRUNS --mutate=$m | grep -E '^\[(pass|FAIL)\]|^mutation' | cut -c1-600; echo "exit ${PIPESTATUS[0]}"
done
} 
