def sha(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()


def lines_of(path):
    return open(path, encoding="utf-8", errors="replace").read().split("\n")


def quote(path, a, b, anchors=(), note=""):
    """Verbatim lines a..b (1-indexed, inclusive); every anchor must occur in the range."""
    L = lines_of(path)[a - 1:b]
    text = "\n".join(L)
    for s in anchors:
        if s not in text:
            fails.append(f"anchor {s!r} not in {path}:{a}-{b}")
            print("FAIL anchor", s, path, a, b)
    out.append(f"`{path}` lines {a}-{b}" + (f" ({note})" if note else "") + ":\n")
    out.append("```tex")
    out.extend(f"{a + i:4d}: {ln}" for i, ln in enumerate(L))
    out.append("```\n")


def must_contain(path, strings):
    t = re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", open(path, encoding="utf-8", errors="replace").read()))
    for s in strings:
        if s not in t:
            fails.append(f"{s!r} not in {path}")
            print("FAIL listing", s, path)


