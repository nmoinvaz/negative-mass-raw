#!/usr/bin/env python3
"""Writes queries.md from rerun/queries.json (written by rerun_queries.py) and, if present, opened.json
(arXiv id or INSPIRE recid -> what was opened and what it bears on). Prints nothing else; every number in queries.md is
computed here from the stored responses.

    python3 -I make_queries_md.py [--in=rerun/queries.json] [--out=queries.md]
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
args = dict(a.lstrip("-").split("=", 1) for a in sys.argv[1:] if "=" in a)
J = json.load(open(os.path.join(HERE, args.get("in", "rerun/queries.json"))))
OUT = os.path.join(HERE, args.get("out", "queries.md"))
op_path = os.path.join(HERE, "opened.json")
OPENED = json.load(open(op_path)) if os.path.exists(op_path) else {}
runs = J["runs"]
NEW = J["new_start"]
KW = ["negative mass", "negative-mass", "negative energy", "phantom", "ghost", "boson star", "naked singularity", "zerilli",
      "bondi", "runaway", "self-accelerat", "wormhole", "positive mass theorem", "positive energy theorem", "adm mass",
      "dominant energy", "opposite sign", "repulsive", "exotic matter", "intertwin"]


def key(h):
    return h.get("id") or ("recid:%s" % h.get("recid"))


def flag(h):
    t = ((h.get("title") or "") + " " + (h.get("summary") or "")).lower()
    return ", ".join(k for k in KW if k in t)


L = []
w = L.append
w("# Rerun of the novelty check's searches after 2026-10-21 (#51)")
w("")
w("Generated by `make_queries_md.py` from `rerun/queries.json` (written by `rerun_queries.py` at %s; responses unchanged in "
  "`rerun/raw/` with sha256 in the json). NEW window: posted %s to the run time; CTRL window 2026-01-01 to 2026-10-20 "
  "(same code path, planted known papers)." % (J["generated"], NEW))
w("")
w("## Controls")
w("")
if J["control_failures"]:
    w("**FAIL**")
    for f in J["control_failures"]:
        w("- " + f)
else:
    w("All controls pass (C1 planted positives, C2 window edge, C3 zero token, C4 citation trail).")
w("")
w("Mutation: `%s`; subset: `%s`." % (J["mutate"] or "none", J["subset"] or "full"))
w("")

# table 1: every query run
w("## Queries run")
w("")
w("`total` is the source's own hit count for the window; `new` counts hits posted on or after %s (arXiv `published`, "
  "INSPIRE earliest date). `kw` counts hits whose title or abstract holds one of the screening words." % NEW)
w("")
w("| id | sect | source | window | query | UTC | total | kw |")
w("|---|---|---|---|---|---|---|---|")
for r in runs:
    if r["section"] in ("K", "T"):
        continue
    q = r["query"].replace("|", "\\|")
    kwn = sum(1 for h in r["hits"] if flag(h))
    w("| %s | %s | %s | %s | `%s` | %s | %s | %s |" % (r["qid"], r["section"], r["source"], r["window"], q, r.get("utc", ""), r["total"], kwn))
w("")

# table 2: new hits, deduplicated
w("## New hits (NEW window), deduplicated")
w("")
agg = {}
for r in runs:
    if r["window"] != "NEW" or r["section"] in ("K", "T"):
        continue
    for h in r["hits"]:
        e = agg.setdefault(key(h), dict(h=h, qs=set()))
        e["qs"].add(r["qid"] + ("/" + r["source"][0]))
w("%d distinct records. `kw` lists the screening words found in title and abstract; a record with no `kw` is listed by title only." % len(agg))
w("")
w("| id | date | title | returned by | kw | opened |")
w("|---|---|---|---|---|---|")
for k, e in sorted(agg.items(), key=lambda kv: -len(kv[1]["qs"])):
    h = e["h"]
    d = (h.get("published") or h.get("date") or "")[:10]
    w("| %s | %s | %s | %s | %s | %s |" % (k, d, (h.get("title") or "").replace("|", "/")[:110], " ".join(sorted(e["qs"])), flag(h), OPENED.get(k, "")))
w("")

# table 3: citation trails
w("## Citation trails (INSPIRE `refersto:recid:` only)")
w("")
w("| paper | recid | citers now (all dates) | new since %s |" % NEW)
w("|---|---|---|---|")
trails = {}
for r in runs:
    if r["section"] != "T":
        continue
    t = trails.setdefault(r["qid"][2:], {})
    t[r["window"]] = r
    t["recid"] = r.get("recid", t.get("recid"))
newcit = []
for name, t in trails.items():
    a, n = t.get("ALLTIME"), t.get("NEW")
    w("| %s | %s | %s | %s |" % (name, t.get("recid", ""), a["total"] if a else "", n["total"] if n else ""))
    if n:
        for h in n["hits"]:
            newcit.append((name, h))
w("")
if newcit:
    w("New citers:")
    w("")
    w("| of | id | date | title | kw | opened |")
    w("|---|---|---|---|---|---|")
    for name, h in newcit:
        w("| %s | %s | %s | %s | %s | %s |" % (name, key(h), h.get("date", ""), (h.get("title") or "").replace("|", "/")[:100], flag(h), OPENED.get(key(h), "")))
    w("")

# table 4: known papers, revisions
w("## Known papers: versions and last update")
w("")
w("| id | versions | published | last update | revised after %s | title |" % NEW)
w("|---|---|---|---|---|---|")
for r in runs:
    if r["section"] != "K":
        continue
    for h in r["hits"]:
        rev = "**yes**" if h["updated"][:10] >= NEW else ""
        w("| %s | v%s | %s | %s | %s | %s |" % (h["id"], h["ver"], h["published"][:10], h["updated"][:10], rev, h["title"][:80].replace("|", "/")))
w("")
open(OUT, "w").write("\n".join(L) + "\n")
