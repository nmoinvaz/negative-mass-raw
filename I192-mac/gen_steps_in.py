#!/usr/bin/env python3
"""Writes multishoot's tests/table_steps.in from proto_table.py's step lists (C3): per case and lane at `last` 4, the
count and every 20th step start. Usage: gen_steps_in.py OUT.in A.json [B.json ...]"""
import json
import sys

out, ins = sys.argv[1], sys.argv[2:]
d = {}
for p in ins:
    d.update(json.load(open(p)))
rows = []
for key in sorted(d):
    case, lane, last = key.split("/")
    if last != "last4" or "start" not in d[key]:
        continue
    st = d[key]["start"]
    samples = ", ".join(f"({i}, {st[i]!r})" for i in range(0, len(st), 20))
    rows.append(f'    ("{case}", "{lane}", {len(st)}, &[{samples}]),')
with open(out, "w") as f:
    f.write("// from negative-mass-raw I192-mac proto_table.py (90-digit decimal arithmetic), `last` 4: case, lane, step count,\n")
    f.write("// every 20th step start (index, x); generated by gen_steps_in.py\n")
    f.write("/// (index, step start)\ntype StepStart = (usize, f64);\n/// (case, lane, step count, every 20th step start)\ntype StepRow = (&'static str, &'static str, usize, &'static [StepStart]);\n")
    f.write("const STEPS: &[StepRow] = &[\n")
    f.write("\n".join(rows) + "\n];\n")
print(len(rows), "rows")
